import math


def area(r):
    '''
    Возвращает площадь круга.
        Параметры:
            r (int/float): радиус круга
        Возвращаемое значение:
            x(float): площадь круга
    '''
    return math.pi * r * r


def perimeter(r):
    '''
    Возвращает длину окружности (периметр круга).
        Параметры:
            r (int/float): радиус круга
        Возвращаемое значение:
            x (float): длина окружности
    '''
    return 2 * math.pi * r

