import math


def area(r):
    '''
    возвращает площадь круга
        параметры:
            r (int|float): радиус круга
        возвращаемое значение:
            x(float): площадь круга
    '''
    return math.pi * r * r


def perimeter(r):
    '''
    возвращает периметр круга
        параметры:
            r (int|float): радиус круга
        возвращаемое значение:
            x (float): периметр круга (длина окружности)
    '''
    return 2 * math.pi * r

